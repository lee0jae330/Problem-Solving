#include<bits/stdc++.h>

using namespace std;

int main() {
	string str;
	cin >> str;
	if (str[0] == 'S') {
		cout << "HIGHSCHOOL" <<'\n';
	}
	else if (str[0] == 'C') {
		cout << "MASTER" <<'\n';
	}
	else if (str[0] == '2') {
		cout << "0611" <<'\n';
	}
	else if (str[0] == 'A') {
		cout << "CONTEST" <<'\n';
	}
}